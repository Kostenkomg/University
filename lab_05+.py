# Вопрос 4.#Эта функция строит таблицу связей слов (базовую модель цепей Маркова). Она анализирует текст и для каждого слова
# запоминает список всех слов, которые могут идти сразу после него. Это нужно для того,
# чтобы потом генерировать случайные тексты в стиле автора.
def build_successors_table(tokens): #• Что происходит: Объявляется функция build_successors_table (в переводе — «построить таблицу последователей»).
#• Параметры: Принимает один аргумент tokens — это упорядоченный список всех слов и знаков препинания из исходного текста
# (например, ['We', 'came', 'to', ...]).
    """Возвращает словарь последующих слов для каждого слова.

    >>> text = ['We', 'came', 'to', 'investigate', ',', 'catch', 'bad', 'guys', 'and', 'to', 'eat', 'pie', '.']
    >>> table = build_successors_table(text)
    >>> sorted(table)
    [',', '.', 'We', 'and', 'bad', 'came', 'catch', 'eat', 'guys', 'investigate', 'pie', 'to']
    >>> table['to']
    ['investigate', 'eat']
    >>> table['pie']
    ['.']
    >>> table['.']
    ['We']
    """
    table = {} #Что происходит: Создается пустой словарь table. Ключами в этом словаре будут уникальные слова из текста,
# а значениями — списки слов, которые встречаются после них.
    previous = '.' #• Зачем это нужно: Создается переменная previous (в переводе — «предыдущее слово»). В самом начале ей искусственно
# присваивается значение точки '.'.
#• Это сделано для того, чтобы связать самое первое слово текста (в примере это 'We') с концом гипотетического прошлого предложения.
# Таким образом, алгоритм будет знать, с каких слов можно начинать новые предложения.
    for word in tokens: #Что происходит: Запускается цикл for, который поочередно перебирает каждое слово (word) из списка tokens
# от начала до конца текста.
        if previous not in table: #Что происходит: Проверка наличия ключа в словаре. Мы смотрим: если слово, сохраненное в previous,
# встречается в цикле впервые и его еще нет среди ключей нашей таблицы table, мы добавляем его туда и закрепляем за ним пустой список [].
            table[previous] = []
        table[previous].append(word) #• Что происходит: Добавление связи. Мы берем список последователей для слова previous
# и с помощью метода .append(word) добавляем туда текущее слово word.
#• Пример: На первой итерации previous равен '.', а word равен 'We'. В таблицу запишется: '.': ['We'].
        previous = word #• Что происходит: Сдвиг фокуса. Текущее слово word выполнило свою роль последователя.
# Теперь оно само становится «предыдущим» словом для следующего шага цикла.
#• Пример: На следующей итерации мы будем искать, какое слово идет уже за словом 'We'.
    return table #Что происходит: После того как цикл обработал весь список токенов, функция возвращает заполненный словарь со всеми связями слов.


