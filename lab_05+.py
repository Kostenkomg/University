#Блок «Деревья» (Конструкторы, селекторы и утилиты)
#Здесь дерево абстрактно представляется в виде обычного списка Python, где первый элемент (индекс 0) — это имя (корень) узла,
# а все остальные элементы — это его ветви (которые сами являются такими же списками-деревьями).
# Например, дерево [1, [2], [3]] означает корень 1 и ветви 2 и 3.
def tree(label, branches=None): #Что происходит: Функция-конструктор, создающая структуру дерева. Принимает имя корня label и необязательный
# список дочерних ветвей branches.
    """Создаёт новое дерево с заданным корневым значением и списком ветвей."""
    if branches is None:
        branches = [] #Что происходит: Защита от мутаций списков по умолчанию. Если список веток не передан,
# создается новый пустой список [] (это означает, что мы создаем "лист").
    for branch in branches: #Что происходит: Цикл проверяет каждую ветку из переданных. Инструкция assert гарантирует:
# если переданный элемент не является валидным деревом (функция is_tree вернет False), программа немедленно прервется
# с ошибкой 'ветви должны быть деревьями'.
        assert is_tree(branch), 'ветви должны быть деревьями'
    return [label] + list(branches) #Что происходит: Создается и возвращается итоговый список. Мы упаковываем корень
# [label] в список и склеиваем его (конкатенируем) со списком ветвей.

#Селекторы (Инструменты чтения данных)
def label(tree):
    """Возвращает корневое значение дерева."""
    return tree[0] #Что происходит: Функция-селектор. Возвращает самый первый элемент списка — корень (имя) переданного дерева.


def branches(tree):
    """Возвращает список ветвей дерева."""
    return tree[1:] #Что происходит: Функция-селектор. Возвращает срез списка со второго элемента и до самого конца —
# то есть чистый список всех дочерних ветвей (без корня).

#Функции-предикаты (Проверки)
def is_tree(tree):
    """Возвращает True, если аргумент — дерево, иначе False."""
    if type(tree) != list or len(tree) < 1:
        return False #Что происходит: Проверка структуры. Объект не может считаться деревом, если он не является списком
# (type(tree) != list) или если он пустой (len(tree) < 1), так как в дереве должен быть как минимум корень. В таких случаях возвращается False.
    return all(is_tree(branch) for branch in branches(tree)) #Что происходит: Рекурсивная проверка. Мы берем все ветви дерева
# и для каждой из них запускаем проверку is_tree. Встроенная функция all() вернет True только тогда, когда абсолютно каждая ветвь успешно
# подтвердит, что она тоже является валидным деревом.


def is_leaf(tree):
    """Возвращает True, если список ветвей пуст, иначе False."""
    return not branches(tree) #Что происходит: Проверяет, является ли узел «листом» (конечной точкой без детей).
# Если у дерева нет ветвей, branches(tree) вернет пустой список []. Логическое not [] превратится в True. Если ветви есть, вернет False.

