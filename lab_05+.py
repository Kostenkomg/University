def print_tree(t, indent=0): #Что происходит: Функция красивого вывода дерева в консоль.
# Принимает дерево t и текущий уровень отступа indent (по умолчанию 0).
    """Выводит дерево с отступом в два пробела на каждый уровень."""
    print('  ' * indent + str(label(t))) #Что происходит: Печатает корень текущего поддерева.
# Строка '  ' * indent умножает два пробела на уровень вложенности, создавая визуальную иерархию (лесенку).
    for branch in branches(t):
        print_tree(branch, indent + 1) #Что происходит: Перебирает все ветви текущего узла и рекурсивно вызывает для них функцию
# print_tree, но увеличивает отступ indent + 1, чтобы дочерние элементы сместились правее в консоли.

#Функция copy_tree предназначена для создания полной независимой копии дерева (в программировании это называется «глубоким копированием» или
# deep copy).Поскольку наши деревья построены на основе обычных списков Python (list), простое копирование ссылки (например, t2 = t)
# привело бы к тому, что изменение одной ветки в t2 испортило бы исходное дерево t. Эта функция решает проблему с помощью рекурсии.
def copy_tree(t):
    """Возвращает независимую копию дерева."""
    return tree(label(t), [copy_tree(branch) for branch in branches(t)]) #1. Внутренняя часть: генератор списка веток
#• branches(t) — селектор возвращает список всех дочерних ветвей текущего дерева t.
#• for branch in branches(t) — цикл поочередно берет каждую ветку.
#• copy_tree(branch) — рекурсивный вызов. Функция запускает саму себя для каждой отдельной ветви. Она будет спускаться глубже и глубже по
# дереву, пока не дойдет до самых нижних листьев.
#• Вся конструкция, обернутая в квадратные скобки [...] (генератор списка или list comprehension), собирает абсолютно новые,
# только что скопированные ветви в один свежий список.
#2. Внешняя часть: сборка нового дерева
#• label(t) — извлекает корневое значение текущего дерева. Значения (числа или строки) в Python копируются безопасно,
# так как они неизменяемы (immutable).
#• tree(..., ...) — вызывается конструктор дерева. Он берет оригинальное имя корня и прикрепляет к нему совершенно новый,
# изолированный список заново скопированных ветвей.
#• return — возвращает полученное новое дерево на уровень выше.
#Как это работает на примере листа:
#Если дерево t — это просто одиночный лист без веток (например, [5]):
#1. branches(t) вернет пустой список [].
#2. Цикл for внутри генератора списка даже не начнет выполняться.
#3. Генератор сразу вернет пустой список [].
#4. Вызовется tree(5, []), который создаст и вернет новый независимый список [5]. Рекурсия начнет подниматься обратно.

